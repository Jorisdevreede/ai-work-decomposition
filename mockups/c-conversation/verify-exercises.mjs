import {createRequire} from 'node:module';
import {writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require('/Users/Joris.deVreede/.npm/_npx/420ff84f11983ee5/node_modules/playwright');
const dir=path.dirname(fileURLToPath(import.meta.url));
const results={checkedAt:new Date().toISOString(),viewports:[],checks:[],touchTargets:[],console:[],pageErrors:[],failedRequests:[],externalRequests:[]};
const browser=await chromium.launch({headless:true,channel:'chrome'});
try {
  for(const width of [1440,390]) {
    const context=await browser.newContext({viewport:{width,height:width===1440?1000:844},reducedMotion:'reduce'});
    const page=await context.newPage();
    page.on('console',m=>{if(['error','warning'].includes(m.type()))results.console.push(m.text());});
    page.on('pageerror',e=>results.pageErrors.push(e.message));
    page.on('requestfailed',r=>results.failedRequests.push(r.url()));
    page.on('request',r=>{if(!r.url().startsWith('http://localhost:8790/')&&!r.url().startsWith('data:'))results.externalRequests.push(r.url());});
    const check=(name)=>results.checks.push({width,name,passed:true});
    const canvas=async()=>{if(width===390)await page.locator('[data-view=canvas]').click();};
    const route=async(target,selector)=>{await page.evaluate(t=>location.hash='#/'+t,target);await page.locator(selector).first().waitFor();};
    const capture=async name=>{
      await page.mouse.move(1,1);
      await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
      await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo({top:0,behavior:'instant'});});
      await page.waitForFunction(()=>scrollY===0);
      await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
      assert.ok(await page.locator('.skip-link').evaluate(e=>e.getBoundingClientRect().bottom<=0),'Skip link is out of the capture');
      if(width===1440)assert.equal(await page.locator('.conversation').evaluate(e=>e.getBoundingClientRect().top),68,'Desktop conversation starts under the header');
      if(width===390){
        const targets=await page.locator('.exercise-progress .text-button,.exercise-work .text-button,.exercise-complete .text-button,.module-evidence .text-button,.exercise-impact .text-button').evaluateAll(els=>els.map(e=>({label:e.textContent.trim(),width:e.getBoundingClientRect().width,height:e.getBoundingClientRect().height})).filter(e=>e.width&&e.height));
        for(const target of targets)assert.ok(target.width>=44&&target.height>=44,`${target.label} has a 44px phone target`);
        results.touchTargets.push({capture:name,targets});
      }
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No horizontal page overflow');
      await page.screenshot({path:path.join(dir,'qa',`${name}-${width}.png`),fullPage:true,animations:'disabled'});
    };
    await page.goto('http://localhost:8790/mockups/c-conversation/index.html#/modules?open=ns-assumptions');
    await page.locator('#module-ns-assumptions a[href="#/exercise?type=assumptions"]').click();
    await page.locator('[data-action=sample-exercise]').waitFor();
    assert.equal(await page.locator('.conversation').isVisible(),true);
    assert.match(await page.locator('#conversation-thread').innerText(),/belief, not evidence/);
    await capture('assumptions-conversation');
    const custom='We believe approved AI drafts could give HR more time for people <not proof>.';
    await page.locator('#message').fill(custom);
    await page.locator('#message').press('Enter');
    assert.match(await page.locator('#conversation-thread').innerText(),/What worries you/);
    await canvas();
    await page.locator('a[href="#/modules"]').filter({hasText:'Pause exercise'}).click();
    await page.locator('#module-ns-assumptions>summary').click();
    await page.locator('#module-ns-assumptions a[href="#/exercise?type=assumptions"]').click();
    await page.locator('[data-action=sample-exercise]').waitFor();
    assert.match(await page.locator('#conversation-thread').innerText(),/more time for people <not proof>/);
    for(let i=0;i<2;i++)await page.locator('[data-action=sample-exercise]').click();
    await page.locator('[data-action=exercise-canvas]').click();
    assert.equal(await page.locator('#exercise-answer-0').inputValue(),custom);
    const reviewed='AI may prepare routine answers. Sensitive advice must have a named HR reviewer.';
    await page.locator('#exercise-answer-0').fill(reviewed);
    await page.locator('[data-exercise-scope="0"]').selectOption('Specific to our team');
    await route('goal','.goal-map');
    assert.equal(await page.locator('.module-evidence').count(),0);
    await page.locator('a[href="#/exercise?type=assumptions"]').click();
    await page.locator('[data-action=exercise-canvas]').click();
    assert.equal(await page.locator('#exercise-answer-0').inputValue(),reviewed);
    const hype=await page.locator('#exercise-answer-2').inputValue();
    await page.locator('#exercise-answer-2').fill('');
    await page.locator('[data-action=save-exercise]').click();
    assert.equal(await page.locator('#exercise-error').isVisible(),true);
    await page.locator('#exercise-answer-2').fill(hype);
    await capture('assumptions-review');
    await page.locator('[data-action=save-exercise]').click();
    await page.locator('.exercise-complete').waitFor();
    assert.equal(await page.locator('.exercise-effects a').count(),3);
    await capture('assumptions-complete');
    check('Assumptions: custom and sample answers, pause/resume, editable map, validation, review gate and completion');
    await page.locator('.exercise-effects a[href="#/team?focus=human-boundaries"]').click();
    await page.locator('#human-boundaries .exercise-impact').waitFor();
    assert.match(await page.locator('#human-boundaries').innerText(),/Sensitive advice must have a named HR reviewer/);
    await capture('team-with-assumptions');
    await route('opportunities?id=support','#opportunity-detail .exercise-impact');
    assert.match(await page.locator('.steps').innerText(),/source and answer accuracy/);
    await route('plan?focus=initiative-Q2','#initiative-Q2 .pilot-check p');
    assert.match(await page.locator('#initiative-Q2').innerText(),/Added by Strategic assumptions/);
    check('Assumptions: saved answers change team boundary, support step and Q2 pilot gate');
    await route('modules?open=ns-inventory','#module-ns-inventory[open]');
    await page.locator('#module-ns-inventory a[href="#/exercise?type=inventory"]').click();
    await page.locator('[data-action=sample-exercise]').waitFor();
    assert.match(await page.locator('#conversation-thread').innerText(),/illustrative; no HR system is connected/);
    for(let i=0;i<3;i++)await page.locator('[data-action=sample-exercise]').click();
    await page.locator('[data-action=exercise-canvas]').click();
    assert.equal(await page.locator('[data-metric-kind="3"]').inputValue(),'Vanity candidate');
    assert.equal(await page.locator('[data-metric-kind="4"]').inputValue(),'Vanity candidate');
    await page.locator('[data-metric-kind="3"]').selectOption('Needs definition');
    await page.locator('[data-action=add-metric]').click();
    await page.locator('[data-metric-name="6"]').fill('Time to correct a payroll error');
    await page.locator('[data-metric-kind="6"]').selectOption('Lagging / outcome');
    await capture('metrics-review');
    await page.locator('[data-action=save-exercise]').click();
    await page.locator('.exercise-complete').waitFor();
    await capture('metrics-complete');
    check('Inventory: today’s sample measures, two vanity flags, changed classification, added measure and completion');
    await page.locator('.exercise-effects a[href="#/opportunities?id=records"]').click();
    await page.locator('#opportunity-detail .exercise-impact').waitFor();
    assert.match(await page.locator('#opportunity-detail').innerText(),/Time to correct a payroll error · Lagging \/ outcome/);
    assert.match(await page.locator('#opportunity-detail').innerText(),/AI prompts sent · Needs definition/);
    await route('plan?focus=initiative-Q1','#initiative-Q1 .pilot-check p');
    assert.match(await page.locator('#initiative-Q1').innerText(),/Lotte agrees measure definitions/);
    await route('plan?focus=initiative-Q4','#initiative-Q4 .exercise-impact');
    assert.match(await page.locator('#initiative-Q4').innerText(),/Vanity candidates stay separate/);
    check('Inventory: reviewed classifications and custom measure persist to the record opportunity and Q1/Q4 plan');
    await route('goal?focus=module-evidence','.module-evidence');
    assert.equal(await page.locator('.evidence-entry').count(),2);
    assert.match(await page.locator('.goal-summary').innerText(),/5 of 5 parts informed/);
    assert.match(await page.locator('.north-star-block').innerText(),/Illustrative/);
    await capture('goal-with-exercises');
    check('Both exercises: two goal contributions, trace links and illustrative North Star retained');
    await route('modules?open=ns-inventory','#module-ns-inventory[open]');
    assert.match(await page.locator('#module-ns-inventory .module-status').innerText(),/Added to goal/);
    assert.match(await page.locator('#module-ns-assumptions .module-status').innerText(),/Added to goal/);
    results.viewports.push({width,passed:true});
    await context.close();
  }
  for(const key of ['console','pageErrors','failedRequests','externalRequests'])assert.equal(results[key].length,0,key);
  results.passed=true;
}catch(error){results.passed=false;results.failure=error.stack;process.exitCode=1;}
finally{await browser.close();await writeFile(path.join(dir,'qa','exercise-results.json'),JSON.stringify(results,null,2));}
console.log(JSON.stringify(results,null,2));
